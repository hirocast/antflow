/* ---- 模様・飾りの繰り返し用 ----
   artRep(n, f)：f(0)〜f(n-1) が返す図形を並べる（f は図形1つ・図形の配列・null のどれかを返す）
   artSag(x, y0, d)：両端が y0、まんなかが y0+d になる「たるんだひも」の高さ */
const artRep = (n, f) => {
  const out = [];
  for (let i = 0; i < n; i++) {
    const r = f(i);
    if (!r) continue;
    if (typeof r[0] === 'string') out.push(r); else out.push(...r);
  }
  return out;
};
