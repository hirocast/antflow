function starPath(g, cx, cy, r1, r2, n) {
  g.beginPath();
  for (let k = 0; k < n * 2; k++) {
    const r = k % 2 ? r2 : r1, a = k * Math.PI / n - Math.PI / 2;
    g.lineTo(cx + r * Math.cos(a), cy + r * Math.sin(a));
  }
  g.closePath();
}
