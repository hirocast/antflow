// 今の女王レベルときせかえから、特別な力を合計する
function perks() {
  const q = (save && save.qlv) || 1, sk = SKINS.find(s => s.k === (save && save.skin)) || SKINS[0], f = sk.fx;
  return {
    coin: 1 + 0.02 * (q - 1) + (f.coin || 0),
    food: 1 + (f.food || 0),
    speed: 1 + (q >= 25 ? 0.1 : 0) + (f.speed || 0),
    combo: 0.6 + (f.combo || 0),
    hintCut: Math.max(q >= 12 ? 0.4 : q >= 5 ? 0.2 : 0, f.hintCut || 0),
    fever: 1 + (q >= 6 ? 0.2 : 0) + (q >= 20 ? 0.2 : 0) + (f.fever || 0),
    feverT: q >= 30 ? 6.5 : 5,
    gold: 1 + (q >= 10 ? 1 : 0) + (f.gold || 0),
    par: 1 + (f.par || 0),
    freeUndo: (q >= 15 ? 3 : q >= 8 ? 2 : q >= 3 ? 1 : 0) + (f.freeUndo || 0),
    freeHint: f.freeHint || 0,
    bonus: f.bonus || 0
  };
}
