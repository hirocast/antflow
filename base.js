// プレイ中（アリの吹き出し）の場面
const TALK_PLAY = new Set(['go', 'pick', 'lift', 'carry', 'home']);
const talkRecent = [];
// 最後に「開始のひとこと」を言ったプレイ（G.run）。やりなおし・別ステージで G.run が変わると、また言う
let talkIntroRun = null;
function stageTalk() {
  if (typeof G === 'undefined' || !G || !G.level) return null;
  return TALK_STAGE[G.level.name] || null;
}
function talkLine(kind, c, theme) {
  const S = stageTalk(), r = Math.random(), play = TALK_PLAY.has(kind), carry = kind === 'pick' || kind === 'carry';
  const run = typeof G !== 'undefined' && G ? G.run : null;
  if (!theme && typeof G !== 'undefined' && G && G.level) theme = G.level.theme;
  let pool = TALK[kind] || TALK.pick;
  if (S && play && run && talkIntroRun !== run) { talkIntroRun = run; pool = S.hi; }
  else if (S && play && kind !== 'lift' && r < 0.34) pool = S.p;
  else if (carry && c != null && c >= 0 && r < 0.48) pool = TALK_COLOR;
  else if (theme && TALK_THEME[theme] && (carry || kind === 'home') && r < 0.6) pool = TALK_THEME[theme];
  else if (S && kind === 'clear' && r < 0.6) pool = S.c;
  else if (S && kind === 'star3' && r < 0.4) pool = S.c;
  else if (S && kind === 'jam' && r < 0.5) pool = S.j;
  else if (S && kind === 'queen' && r < 0.35) pool = S.q;
  if (!pool || !pool.length) pool = TALK[kind] || TALK.pick;
  let s = pool[0];
  for (let k = 0; k < 8; k++) { s = pick(pool); if (talkRecent.indexOf(s) < 0) break; }
  talkRecent.push(s);
  if (talkRecent.length > 30) talkRecent.shift();
  return s.replace('{c}', c != null && c >= 0 ? COLOR_NAME[c] : '');
}

